export type OpenPr = {
  repo: string;
  ref: string;
  title: string;
  url: string;
  opened: string;
  age_days: number;
  ci: 'green' | 'red' | 'pending' | 'none';
  draft: boolean;
  unresolved_comments: number;
  plane_url: string;
};
export type DeployRow = {
  repo: string;
  ref: string;
  title: string;
  pr_url: string;
  merged_at: string;
  action: string;
};
export type LastRun = {
  started: string;
  ended: string;
  sessions: number;
  prs_opened: number;
  feedback_handled: number;
  stop_reason: string;
  telemetry: string;
  swept?: number;
  labelled_bau?: number;
  labelled_not_bau?: number;
  triaged?: number;
  asked?: number;
};
export type Question = { id: string; text: string; recommendation: string; why: string };
export type QuestionRow = {
  repo: string;
  ref: string;
  title: string;
  plane_url: string;
  repo_url: string;
  asked_at: string;
  age_days: number;
  round: number;
  summary: string;
  questions: Question[];
};
export type NudgeLevel = 'ok' | 'warn' | 'down';
export type Nudge = { level: NudgeLevel; prs: NudgeLevel; questions: NudgeLevel };
export type Answer = { id: string; accepted: boolean; text: string };
export type Pace = {
  five_hour_used: number;
  five_hour_resets: number;
  seven_day_used: number;
  seven_day_resets: number;
  elapsed_pct: number;
};
export type BuildVersion = { version: string; sha: string };
export type Snapshot = {
  schema: number;
  version?: BuildVersion;
  missing?: boolean;
  generated_at?: string;
  paused?: boolean;
  last_run?: LastRun | null;
  pace?: Pace | null;
  open_prs?: OpenPr[];
  deploy_pending?: DeployRow[];
  questions?: QuestionRow[];
  nudge?: Nudge;
  uninstalled?: string[];
  unreadable?: string[];
  declined?: { ref: string; reason: string; at: string }[];
};
